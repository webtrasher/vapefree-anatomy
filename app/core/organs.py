"""Модули здоровья по органам: что показываем, таймлайны, вейп-специфика.

Каждый модуль задаёт набор опорных точек (milestone). Точки привязаны к
часам непрерывного воздержания и проценту восстановления, выведенному из
данных ВОЗ / CDC / NHS / пульмонологических и кардиологических исследований.

Промежуточные значения интерполируются в логарифмическом времени
(см. app.core.recovery.RecoveryCurve): восстановление идёт быстро в первые
часы и дни и замедляется на длинной дистанции.
"""

from __future__ import annotations

from dataclasses import dataclass, field

HOUR = 1.0
DAY = 24.0


@dataclass(frozen=True)
class Milestone:
    """Опорная точка таймлайна."""

    hours: float
    percent: float
    title: str
    detail: str
    sources: tuple[str, ...] = ()

    @property
    def days(self) -> float:
        return self.hours / DAY


@dataclass(frozen=True)
class OrganModule:
    """Модуль здоровья одного органа или системы."""

    key: str
    name: str
    short: str
    emoji: str
    headline: str
    what_we_show: tuple[str, ...]
    milestones: tuple[Milestone, ...]
    vape_specific: str
    ritual_note: str = ""
    sources: tuple[str, ...] = field(default=())

    @property
    def full_recovery_days(self) -> float:
        return self.milestones[-1].days

    def milestone_reached(self, hours: float) -> Milestone | None:
        """Последняя достигнутая опорная точка."""
        reached = [m for m in self.milestones if hours >= m.hours]
        return reached[-1] if reached else None

    def next_milestone(self, hours: float) -> Milestone | None:
        """Ближайшая будущая опорная точка."""
        for m in self.milestones:
            if hours < m.hours:
                return m
        return None


def _m(hours: float, percent: float, title: str, detail: str, *sources: str) -> Milestone:
    return Milestone(hours=hours, percent=percent, title=title, detail=detail, sources=tuple(sources))


